export function getPartDefinition(id) {
  if (PART_DEFS[id]) return PART_DEFS[id];

  if (id.startsWith("mainProduct-")) {
    const [, row, col] = id.split("-");
    return {
      name: `产品 P${String(Number(row) + 1).padStart(2, "0")}${String(Number(col) + 1).padStart(2, "0")}`,
      category: "输送系统 / 产品阵列",
      function: "主检测料盘中的独立 PCS 产品位，可标记缺料并由真空吸嘴补充。",
      params: ["坐标：" + `R${Number(row) + 1} C${Number(col) + 1}`, "单件：" + metric(24), "状态：实时同步"],
      install: "主检测料盘",
      motion: "随料盘移动 · 补料时由吸嘴搬运",
    };
  }

  if (id.startsWith("supplyProduct-")) {
    const [, row, col] = id.split("-");
    return {
      name: `供料单元 S${Number(row) + 1}-${Number(col) + 1}`,
      category: "供料系统 / 独立供料盘",
      function: "独立供料盘中的备用产品，等待 XYZ 真空吸嘴取料。",
      params: ["阵列坐标：" + `R${Number(row) + 1} C${Number(col) + 1}`, "状态：待取 / 已取", "供货：连续"],
      install: "独立供料盘",
      motion: "固定 · 被吸取后随吸嘴移动",
    };
  }

  return {
    name: "未命名部件",
    category: "设备",
    function: "机械部件",
    params: ["等待参数录入"],
    install: "设备内部",
    motion: "固定",
  };
}

